def step(identifier, title, role, kind, quote, *, systems=(), documents=(), duration=None):
    return Step(
        id=identifier, title=title, role_id=role, type=kind, quote=quote,
        confidence=1, systems=list(systems), documents=list(documents), duration_minutes=duration,
    )


def edge(identifier, origin, target, label, quote):
    return Edge(id=identifier, from_step=origin, to_step=target, label=label, quote=quote)


def loss(identifier, title, steps, loss_type, cause, quote, *, minutes=None, rubles=None, basis=None):
    basis = basis or (
        "Замер участника встречи из стенограммы. Стоимость операции не указана."
        if minutes is not None else
        "В стенограмме нет измеренной длительности и стоимости этой потери."
    )
    return Bottleneck(
        id=identifier, title=title, step_ids=steps, loss_type=loss_type, cause=cause, quote=quote,
        time_minutes=minutes, cost_rub=rubles, metric_basis=basis,
    )


def proposal(identifier, title, bottleneck, quote, description, effect, calculation, complexity, risk, priority, *,
             saving=None):
    return Recommendation(
        id=identifier, title=title, bottleneck_ids=[bottleneck], quote=quote, description=description,
        effect=effect, estimated_saving_minutes=saving, calculation=calculation,
        complexity=complexity, risk=risk, priority=priority,
    )


def build_analysis(example, role_names, steps, edges, bottlenecks, recommendations, *, warnings=()):
    return Analysis(
        schema_version="1.0", title=example.title, source_text=example.text, mode="demo",
        demo_id=example.id, roles=[Role(id=id_, name=name) for id_, name in role_names.items()],
        steps=steps, edges=edges, bottlenecks=bottlenecks, recommendations=recommendations, edited=False,
        warnings=[*warnings, "Сохранённый разбор синтетической стенограммы. Эффекты автоматизации требуют проверки."],
    )


